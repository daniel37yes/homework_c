/*
 * G4.c
 * 
По одному разу
В файле .txt даны два слова не более 100 символов каждое, разделенные 
одним пробелом. Найдите только те символы слов, которые встречаются в 
обоих словах только один раз. Напечатайте их через пробел в файл .txt 
в лексикографическом порядке. 

Данные на входе: 	Два слова из маленьких английских букв через пробел. 
					Длинна каждого слова не больше 100 символов. 
Данные на выходе: 	Маленькие английские буквы через пробел. 

Пример №1
Данные на входе: 	hello world 
Данные на выходе: 	o 


Данные на входе: 	aabcd bcef 
Данные на выходе: 	b c 

 */

#include <stdio.h>
#include <string.h>
#include <ctype.h>

#define MAX_LEN 101

int main() {
    FILE *input = fopen("input.txt", "r");
    FILE *output = fopen("output.txt", "w");

    char word1[MAX_LEN], word2[MAX_LEN];
    fscanf(input, "%s %s", word1, word2); // Читаем два слова

    int count1[26] = {0}; // Частота символов в первом слове
    int count2[26] = {0}; // Частота символов во втором слове

    // Подсчёт символов в первом слове
    for (int i = 0; word1[i] != '\0'; i++) {
        count1[word1[i] - 'a']++;
    }

    // Подсчёт символов во втором слове
    for (int i = 0; word2[i] != '\0'; i++) {
        count2[word2[i] - 'a']++;
    }

    // Поиск символов, встречающихся ровно 1 раз в каждом слове
    for (char c = 'a'; c <= 'z'; c++) {
        int idx = c - 'a';
        if (count1[idx] == 1 && count2[idx] == 1) {
            fprintf(output, "%c ", c);
        }
    }

    fclose(input);
    fclose(output);
    return 0;
}
