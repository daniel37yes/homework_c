/*
 * F16.c
 * 
Клетки
Известно, что шахматная доска имеет размерность 8х8 и состоит из клеток 2х цветов, 
например, черного и белого (см. рисунок). Каждая клетка имеет координату, 
состоящую из буквы и цифры. Горизонтальное расположение клетки определяется 
буквой от A до H, а вертикальное – цифрой от 1 до 8. 
Заметим, что клетка с координатой А1 имеет черный цвет. 
Требуется по заданной координате определить цвет клетки.


Данные на входе: 	В единственной строке записана координата клетки на 
					шахматной доске: всего два символа – буква и цифра 
					(без пробелов). 
Данные на выходе: 	В выходной файл нужно вывести «WHITE», если 
					указанная клетка имеет белый цвет и «BLACK», если она черная. 

Пример №1
Данные на входе: 	C3 
Данные на выходе: 	BLACK 

Пример №2
Данные на входе: 	G8 
Данные на выходе: 	WHITE
 */



#include <stdio.h>
#include <ctype.h>

int main() {
    char coord[3];  // Для хранения координаты (буква + цифра + '\0')
    
    
    scanf("%2s", coord);  // Читаем ровно 2 символа
    
    // Преобразуем букву в номер столбца (A=0, B=1, ..., H=7)
    int col = toupper(coord[0]) - 'A';
    
    // Преобразуем цифру в номер строки (1=0, 2=1, ..., 8=7)
    int row = coord[1] - '1';
    
    // Определяем цвет: если сумма номера столбца и строки четная - BLACK, иначе WHITE
    if ((col + row) % 2 == 0) {
        printf("BLACK\n");
    } else {
        printf("WHITE\n");
    }
    
    return 0;
}
