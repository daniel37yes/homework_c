#include <stdio.h>

void swap_negmax_last(int size, int a[]) {
    int max_neg = 0;          // Значение максимального отрицательного элемента
    int max_neg_index = -1;   // Индекс максимального отрицательного элемента
    
    // Поиск максимального отрицательного элемента
    for (int i = 0; i < size; i++) {
        if (a[i] < 0) {       // Если элемент отрицательный
            if (max_neg == 0 || a[i] > max_neg) {
                max_neg = a[i];
                max_neg_index = i;
            }
        }
    }
    
    // Если нашли отрицательный элемент, меняем его с последним
    if (max_neg_index != -1) {
        int temp = a[max_neg_index];
        a[max_neg_index] = a[size-1];
        a[size-1] = temp;
    }
}

int main() {
    int arr[100];             // Массив для хранения чисел
    int size = 0;             // Размер массива
    int num;                  // Переменная для чтения чисел
    
    
    // Чтение чисел с консоли
    while (scanf("%d", &num) == 1) {
        arr[size++] = num;
        if (size >= 100) break;  // Защита от переполнения массива
    }
    
    // Очистка буфера ввода
    while (getchar() != '\n');
    
    
    //~ for (int i = 0; i < size; i++) {
        //~ printf("%d ", arr[i]);
    //~ }
    
    // Вызов функции для обработки массива
    swap_negmax_last(size, arr);
    
   
    for (int i = 0; i < size; i++) {
        printf("%d ", arr[i]);
    }
    
    return 0;
}
