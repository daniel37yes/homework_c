int compression(int a [], int b [], int N) {
    int b_n = 0;
    int curr = 0;
    int prew = 0;


    for(int i = 0; i < N; i++) {
        if(a[i] != curr) {
            curr = a[i];
            b[b_n++] = i - prew;
            prew = i;
            i--;
        }
        else if(i == N - 1)
            b[b_n++] = i - prew + 1;
    }




    return b_n;
}







int compression(int a[], int b[], int N) {
    if (N == 0) return 0; // Пустой массив
    
    int count = 0; // Счетчик элементов в результирующем массиве
    int current = a[0]; // Текущий элемент серии
    int length = 1; // Длина текущей серии
    
    // Если массив начинается с 1, добавляем 0 в начало
    if (current == 1) {
        b[count++] = 0;
    }
    
    // Проходим по массиву, начиная со второго элемента
    for (int i = 1; i < N; i++) {
        if (a[i] == current) {
            length++; // Увеличиваем длину текущей серии
        } else {
            // Записываем длину завершенной серии
            b[count++] = length;
            // Начинаем новую серию
            current = a[i];
            length = 1;
        }
    }
    
    // Добавляем длину последней серии
    b[count++] = length;
    
    return count; // Возвращаем количество элементов в сжатом массиве
}
