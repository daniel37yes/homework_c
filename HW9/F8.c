/*
 * F8.c
 * 
 Пропущенное число
Написать функцию и программу, демонстрирующую работу данной функции.
В последовательности записаны целые числа от M до N 
( M меньше N, M больше или равно 1) в произвольном порядке, но одно из 
чисел пропущено (остальные встречаются ровно по одному разу). N не 
превосходит 1000. Последовательность заканчивается числом 0. 
Определить пропущенное число. 

Данные на входе:    Последовательность целых чисел от M до N. M, N не превосходит 1000. 
Данные на выходе:   Одно целое число 

Пример №1
Данные на входе:    2 3 1 4 7 6 9 8 10 0 
Данные на выходе:   5 

Пример №2
Данные на входе:    41 40 39 38 37 36 34 33 32 31 50 49 48 47 46 45 44 43 42 30 0 
Данные на выходе:   35
 */


#include <stdio.h>
#include <stdlib.h>

int find_missing_number() {
    int num;
    int min = 1001;  // Минимальное значение (M)
    int max = 0;     // Максимальное значение (N)
    int sum = 0;     // Сумма введенных чисел
    int count = 0;   // Количество чисел
    
    // Чтение последовательности и вычисление параметров
    while (1) {
        scanf("%d", &num);
        if (num == 0) break;
        
        if (num < min) min = num;
        if (num > max) max = num;
        sum += num;
        count++;
    }
    
    // Вычисление ожидаемой суммы по формуле суммы арифметической прогрессии
    int expected_sum = (min + max) * (max - min + 1) / 2;
    
    // Пропущенное число - разница между ожидаемой и фактической суммой
    return expected_sum - sum;
}

int main() {
    int missing = find_missing_number();
    printf("%d\n", missing);
    return 0;
}
